def parent_of(c):
    return {'district': DISTRICT, 'oblast': OBLAST, None: None}[c.get('parent', 'district')]


def chain_of(c):
    """Батьківські сторінки від найвищої: [OBLAST, DISTRICT]."""
    out, p = [], parent_of(c)
    while p:
        out.insert(0, p)
        p = parent_of(p)
    return out


def children_of(c):
    kids = [x for x in [DISTRICT] + CITIES if parent_of(x) is c]
    return kids


def place_schema(c):
    """areaServed з вкладеністю: місто → район → область → Україна."""
    node = {"@type": KIND_SCHEMA[c['kind']], "name": c['name']}
    cur = node
    for p in reversed(chain_of(c)):
        cur["containedInPlace"] = {"@type": "AdministrativeArea", "name": p['name']}
        cur = cur["containedInPlace"]
    cur["containedInPlace"] = {"@type": "Country", "name": "Україна"}
    return node


